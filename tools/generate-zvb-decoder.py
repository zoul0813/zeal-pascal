#!/usr/bin/env python3
"""Generate the bounded RAM decoder leaf; jumps remain link-relocated Inline words."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
class Stream:
 def __init__(self):self.data=bytearray();self.labels={};self.words={}
 def emit(self,hex_bytes):self.data.extend(bytes.fromhex(hex_bytes))
 def label(self,name):assert name not in self.labels;self.labels[name]=len(self.data)
 def jump(self,opcode,target):self.emit(opcode);self.words[len(self.data)]=target;self.emit('0000')
 def result(self):
  parts=[];at=0
  while at<len(self.data):
   if at in self.words:
    delta=self.labels[self.words[at]]-at
    parts.append('*'+('+'if delta>=0 else '-')+str(abs(delta)));at+=2
   else:parts.append('$%02X'%self.data[at]);at+=1
  return '/\n    '.join('/'.join(parts[i:i+14])for i in range(0,len(parts),14))
a=Stream();e=a.emit;j=a.jump;l=a.label
# IY=state, DE=256-byte history. Preserve both Pascal frame/index registers.
e('FDE5 DD6E06 DD6607 E5 FDE1 DD5E04 DD5605')
e('FD7E0A B7');j('C2','emit')
l('token');j('CD','source');j('DA','done')
e('4F FD7E0F FE10');j('CA','rle')
e('79 FE40');j('DA','single')
e('FE80');j('DA','lz_literal')
e('FD360B02') # RunKind=history
e('79 FEC0');j('D2','long_history')
e('E60F 3C FD770C FD360D00 79 0F0F0F0F E603 C603 FD770A');j('C3','history_check')
l('long_history');e('E63F C604 FD770A');j('CD','source');j('DA','invalid')
e('6F2600 23 FD750C FD740D')
l('history_check');e('FD6E08 FD6609 FD4E0C FD460D B7 ED42');j('DA','invalid');j('C3','budget')
l('single');e('FD770E FD360A01 FD360B00');j('C3','budget')
l('lz_literal');e('E63F');j('C3','literal')
l('rle');e('79 FE80');j('DA','literal')
e('E67F 3C FD770A FD360B00');j('CD','source');j('DA','invalid');e('FD770E');j('C3','budget')
l('literal');e('3C FD770A FD360B01 FD7E03 B7');j('C2','budget')
e('FD7E02 FDBE0A');j('DA','invalid')
l('budget');e('FD4E0A 0600 FD6E04 FD6605 FD7E10 B7');j('C2','full_budget')
e('B7 ED42');j('DA','invalid');j('C3','store_budget')
l('full_budget');e('B7 ED42 FD361000')
l('store_budget');e('FD7504 FD7405 FD6E08 FD6609 09 7C B7');j('CA','known')
e('210001')
l('known');e('FD7508 FD7409')
l('emit');e('FD7E0B FE01');j('CA','emit_literal')
e('FE02');j('CA','emit_history')
e('FD7E0E');j('C3','store')
l('emit_literal');j('CD','source');j('DA','invalid');j('C3','store')
l('emit_history');e('FD7E06 FD960C 6F2600 19 7E')
l('store');e('4F FD6E06 2600 19 71 FD350A FD3406');j('CA','chunk')
e('FD7E0A B7');j('C2','emit');j('C3','token')
l('chunk');e('FD360701');j('C3','finish')
l('invalid');e('FD361202')
l('done');e('FD361101');j('C3','finish')
# Read one source byte. Carry reports EOF; no stack escape from this helper.
l('source');e('FD4E02 FD4603 78 B1');j('C2','source_available');e('37 C9')
l('source_available');e('0B FD7102 FD7003 FD6E00 FD6601 7E 23 FD7500 FD7401 B7 C9')
l('finish');e('FDE1')
# State byte offsets: input0,left2,budget4,position6,known8,count10,run11,
# offset12,value14,kind15,full16,done17,error18.
text='''{ Generated by tools/generate-zvb-decoder.py. RAM-only circular decoder.
  Validate tokens before emitting; pending runs survive full chunks.
  Internal CALL/JP words relocate through Inline * expressions. }
type TEncodedState = record
  InputAddress, InputLeft, Remaining, Position, Known: Word;
  Count, RunKind: Byte;
  Offset: Word;
  Value, Kind: Byte;
  Full, Done: Boolean;
  Error: Byte
end;
procedure DecodeEncoded(var State: TEncodedState; var Pixels);
begin
  Inline(
    '''+a.result()+''')
end;
'''
path=ROOT/'units/zvb/ZVBDECODE.INC'
if __name__=='__main__':
 if sys.argv[1:]==['--check']:
  if path.read_text()!=text:raise SystemExit('Regenerate units/zvb/ZVBDECODE.INC')
 elif not sys.argv[1:]:path.write_text(text)
 else:raise SystemExit('usage: generate-zvb-decoder.py [--check]')
 print('Decoder bytes:',len(a.data),'relocated internal words:',len(a.words))
